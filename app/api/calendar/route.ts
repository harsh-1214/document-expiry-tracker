import { NextResponse } from "next/server";

/** Payload shape expected from the client. */
interface CalendarSyncPayload {
  docType: string;
  nickname: string;
  expiryDate: string; // YYYY-MM-DD
  accessToken: string;
}

/**
 * POST /api/calendar
 *
 * Proxies a Google Calendar event creation request server-side so that the
 * OAuth access token is never exposed in client-side network logs beyond the
 * initial request to this route.
 *
 * Zero-retention guarantee: only the 3 allowed metadata fields (docType,
 * nickname, expiryDate) are forwarded to Google. No image data, document ID
 * numbers, or addresses are included in the calendar payload.
 */
export async function POST(req: Request) {
  try {
    // ── 1. Parse & validate payload ─────────────────────────────────────────
    const body: unknown = await req.json();

    if (
      typeof body !== "object" ||
      body === null ||
      typeof (body as Record<string, unknown>).docType !== "string" ||
      typeof (body as Record<string, unknown>).nickname !== "string" ||
      typeof (body as Record<string, unknown>).expiryDate !== "string" ||
      typeof (body as Record<string, unknown>).accessToken !== "string"
    ) {
      return NextResponse.json(
        { success: false, error: "Missing or invalid fields: docType, nickname, expiryDate, accessToken are all required." },
        { status: 400 }
      );
    }

    const { docType, nickname, expiryDate, accessToken } =
      body as CalendarSyncPayload;

    // ── Rule 6 §Ephemeral Auth ───────────────────────────────────────────────
    // accessToken is used ONLY to set the Authorization header below.
    // It is NEVER logged, written to a database, returned in a response body,
    // or stored anywhere. It exists only for the lifetime of this request.

    // ── Rule 6 §Payload Minimization ────────────────────────────────────────
    // summary: only nickname + docType (user-confirmed metadata).
    // description: static string — no raw extraction output, JSON dumps,
    //              image data, document ID numbers, or addresses.
    const calendarEvent = {
      summary: `Renewal Required: ${nickname} (${docType})`,
      description:
        "Automated privacy-first reminder generated by Document Expiry Tracker.",
      start: { date: expiryDate },
      end: { date: expiryDate },
      reminders: {
        useDefault: false,
        overrides: [
          { method: "email", minutes: 43200 }, // 30 days
          { method: "popup", minutes: 43200 }, // 30 days
          { method: "email", minutes: 10080 }, //  7 days
          { method: "popup", minutes: 10080 }, //  7 days
        ],
      },
    };

    // ── 3. POST to the Google Calendar API ──────────────────────────────────
    const gcalRes = await fetch(
      "https://www.googleapis.com/calendar/v3/calendars/primary/events",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${accessToken}`,
        },
        body: JSON.stringify(calendarEvent),
      }
    );

    // ── 4. Surface Google's error verbatim so the client can show it ─────────
    if (!gcalRes.ok) {
      let googleError = `Google Calendar API error: ${gcalRes.status} ${gcalRes.statusText}`;
      try {
        const errBody = await gcalRes.json() as { error?: { message?: string } };
        if (errBody?.error?.message) {
          googleError = errBody.error.message;
        }
      } catch {
        // Non-JSON error body — keep the status string above.
      }
      console.error("[calendar] Google API error:", googleError);
      return NextResponse.json({ success: false, error: googleError }, { status: gcalRes.status });
    }

    return NextResponse.json({ success: true });
  } catch (error: unknown) {
    // Rule 6 §Ephemeral Auth: never log the request body — it contains
    // the accessToken. Log only the sanitised error message.
    console.error("[calendar] Route error:", error instanceof Error ? error.message : String(error));
    const message = error instanceof Error ? error.message : String(error);
    return NextResponse.json({ success: false, error: message }, { status: 500 });
  }
}

