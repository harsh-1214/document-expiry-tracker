import { NextResponse } from "next/server";

/** Payload shape expected from the client. */
interface CalendarSyncPayload {
  docType: string;
  nickname: string;
  expiryDate: string;   // YYYY-MM-DD
  accessToken: string;
  testMode?: boolean;   // if true, schedule event 5 min from now with immediate popup
}

/**
 * POST /api/calendar
 *
 * Proxies a Google Calendar event creation request server-side.
 * Rule 6 §Ephemeral Auth: accessToken is used only to set the Authorization
 * header and is never logged, stored, or returned.
 * Rule 6 §Payload Minimization: only nickname, docType, expiryDate (and static
 * description text) reach Google. No images, IDs, or addresses.
 */
export async function POST(req: Request) {
  try {
    // ── 1. Parse & validate payload ─────────────────────────────────────────
    const body: unknown = await req.json();

    if (
      typeof body !== "object" ||
      body === null ||
      typeof (body as Record<string, unknown>).docType !== "string" ||
      typeof (body as Record<string, unknown>).nickname !== "string" ||
      typeof (body as Record<string, unknown>).expiryDate !== "string" ||
      typeof (body as Record<string, unknown>).accessToken !== "string"
    ) {
      return NextResponse.json(
        { success: false, error: "Missing or invalid fields: docType, nickname, expiryDate, accessToken are all required." },
        { status: 400 }
      );
    }

    const { docType, nickname, expiryDate, accessToken, testMode } =
      body as CalendarSyncPayload;

    // ── Rule 6 §Ephemeral Auth ───────────────────────────────────────────────
    // accessToken is used ONLY in the Authorization header below.
    // It is NEVER logged, stored in a DB, returned in a response, or cached.

    // ── 2. Build the Google Calendar event body ──────────────────────────────
    // Rule 6 §Payload Minimization: summary contains only nickname + docType;
    // description is static text. No raw extraction output or JSON dumps.
    let calendarEvent: object;

    let startDateTime, endDateTime, timeZone, summary, description, overrides;

    if (testMode) {
      // Test Alert: Exactly 5 minutes from right now
      const now = new Date();
      const start = new Date(now.getTime() + 5 * 60000);
      const end = new Date(start.getTime() + 35 * 60000); // 30 min duration
      
      startDateTime = start.toISOString();
      endDateTime = end.toISOString();
      timeZone = "UTC"; // toISOString generates UTC
      summary = `[TEST ALERT] Renewal: ${nickname}`;
      description = "TEST EVENT: Privacy-first reminder generated by Document Expiry Tracker.";
      overrides = [{ method: "popup", minutes: 0 }]; // Ping immediately at the test time
    } else {
      // Standard Sync: Lock to 9:00 AM IST on the provided YYYY-MM-DD date
      startDateTime = `${expiryDate}T09:00:00+05:30`;
      endDateTime = `${expiryDate}T09:30:00+05:30`;
      timeZone = "Asia/Kolkata";
      summary = `Renewal Required: ${nickname} (${docType})`;
      description = "Automated privacy-first reminder generated by Document Expiry Tracker. Please initiate renewal.";
      overrides = [
        { method: "popup", minutes: 43200 }, // 30 days before at 9:00 AM
        { method: "email", minutes: 43200 }, // 30 days before at 9:00 AM
        { method: "popup", minutes: 10080 }, // 7 days before at 9:00 AM
        { method: "email", minutes: 10080 }, // 7 days before at 9:00 AM
      ];
    }

    calendarEvent = {
      summary,
      description,
      start: { dateTime: startDateTime, timeZone },
      end: { dateTime: endDateTime, timeZone },
      reminders: {
        useDefault: false,
        overrides,
      },
    };

    // ── 3. POST to the Google Calendar API ──────────────────────────────────
    const gcalRes = await fetch(
      "https://www.googleapis.com/calendar/v3/calendars/primary/events",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${accessToken}`,
        },
        body: JSON.stringify(calendarEvent),
      }
    );

    // ── 4. Surface Google's error so the client can show it ──────────────────
    if (!gcalRes.ok) {
      let googleError = `Google Calendar API error: ${gcalRes.status} ${gcalRes.statusText}`;
      try {
        const errBody = await gcalRes.json() as { error?: { message?: string } };
        if (errBody?.error?.message) googleError = errBody.error.message;
      } catch {
        // Non-JSON error body — keep the status string above.
      }
      console.error("[calendar] Google API error:", googleError);
      return NextResponse.json(
        { success: false, error: googleError },
        { status: gcalRes.status }
      );
    }

    return NextResponse.json({ success: true });
  } catch (error: unknown) {
    // Rule 6 §Ephemeral Auth: log only the message, not the full body (avoids
    // any chance of the accessToken appearing in server logs).
    const message = error instanceof Error ? error.message : String(error);
    console.error("[calendar] Route error:", message);
    return NextResponse.json({ success: false, error: message }, { status: 500 });
  }
}
